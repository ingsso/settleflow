package com.settleflow.reconciliation.domain;

/**
 * 외부 축 불일치의 종류(W3D4 — ⑤). <b>원인이 서로 달라서 가른다.</b>
 *
 * <p>계획서가 넷으로 잡았던 것 중 <i>"둘 다 있는데 상태가 다름"</i> 이 없다.
 * <b>정산 리포트에는 실패한 거래가 없어서</b>(거절은 정산될 돈이 없다) 상태 칸 자체를 두지 않았고,
 * 그래서 상태 차이가 <b>있음/없음으로 흡수됐다</b>({@code PgReportRow} javadoc).
 */
public enum PgDiscrepancyType {

    /**
     * PG 리포트엔 있는데 우리에겐 없다. <b>외부 축의 상금이자, 내부 축이 절대 못 잡는 것.</b>
     *
     * <p>전형적 원인은 <b>웹훅 유실</b>이다 — 고객은 돈을 냈고 PG 는 승인했는데 우리는 주문을
     * 안 만들었다. 우리 안엔 기록 자체가 없으므로 장부·정산을 아무리 맞춰봐도 나오지 않는다
     * (B 축이 못 잡는 이유). <b>바깥을 봐야만 보인다.</b>
     */
    ONLY_IN_REPORT,

    /**
     * 우리에겐 있는데 리포트에 없다. <b>두 가지가 섞여 있다</b> —
     * <i>아직 안 온 것</i>(정산 주기가 걸쳐 다음 파일에 실릴 건)과 <i>영영 안 올 것</i>.
     *
     * <p>둘을 여기서 가를 수 없다. 가르려면 며칠치 리포트를 이어 봐야 하고, 그건 이 대사의
     * 스코프 밖이다. 그래서 이 종류는 <b>즉시 경보가 아니라 관찰 대상</b>이다.
     *
     * <p>{@code UNKNOWN} 결제도 여기 나타나지 않는다 — 애초에 우리가 PAID 로 안 봤으므로 내부
     * 목록에 없다. {@code UNKNOWN} 의 진실은 반대편({@link #ONLY_IN_REPORT})에서 채워진다.
     */
    ONLY_IN_INTERNAL,

    /**
     * 양쪽에 다 있는데 금액이 다르다.
     *
     * <p>비교하는 건 {@code gross}(승인금액/환불금액) 하나다. PG 수수료·입금액은 리포트에 실려
     * 오지만 <b>쓰지 않는다</b> — 우리 장부에 대응 계정이 없어(④-나) 비교하면 매 건 차이가 나고,
     * 그건 버그가 아니라 <b>모델에 계정이 없어서 생기는 구조적 차이</b>다.
     */
    AMOUNT_MISMATCH
}
