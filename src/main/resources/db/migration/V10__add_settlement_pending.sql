-- =========================================
-- V10__add_settlement_pending.sql
-- 정산의 "진행" 축(W3D5). W3D3 §4 가 뚫어놓고 갚기로 한 구멍을 여기서 닫는다.
--
-- ── 구멍 ──────────────────────────────────────────────────────────────────
-- journal.created_at 은 persist 시점에 JVM 이 찍고(Journal.onCreate), 그 행이 다른
-- 트랜잭션에 보이는 건 커밋 시점이다. 둘 사이에 간격이 있다:
--
--   26일 23:59:59  created_at 찍힘
--   27일 02:00:00  26일자 배치 실행   ← 아직 커밋 전이라 이 줄을 못 봄
--   27일 02:00:05  커밋              ← 27일 배치엔 created_at 이 범위 밖
--
-- 어느 정산에도 안 들어간다. 놓친 게 아니라 증발한다.
--
-- ── 원인 ──────────────────────────────────────────────────────────────────
-- 배치의 WHERE 한 줄이 서로 다른 두 질문에 동시에 답하고 있었다:
--
--   "이 줄은 언제 귀속되는가"  → created_at.  persist 때 멈추는 시계
--   "이 줄을 이미 셌는가"      → 가시성.      커밋 때 움직이는 시계
--
-- 시계가 둘인데 컬럼이 하나였다. 그래서 W3D3 §4 의 표는 (가) 시간으로 자르기 /
-- (나) 상태로 자르기를 배타적으로 그렸고, "증발 없음"과 "26일자 매출의 뜻이 깨끗함"이
-- 양자택일처럼 보였다. 그 표가 틀렸다 — 두 다이얼을 하나로 묶어 그렸을 뿐이다.
--
-- ── 이 테이블 ─────────────────────────────────────────────────────────────
-- 축을 나눈다. 귀속은 created_at 이 그대로 답하고(그래서 "26일자 매출"의 뜻이 안 흐려진다),
-- 진행은 이 테이블이 답한다(그래서 늦게 커밋된 줄이 제 날짜로 주워진다). 둘 다 얻는다.
--
-- 모양은 아웃박스(V6)와 같다 — 아직 처리 안 된 것만 담고, 처리하면 지운다. 아웃박스가
-- 이 구멍을 안 겪는 이유가 바로 그거였다(publishedAt IS NULL, 시간을 안 쓴다). 다른 점은
-- 정산엔 축이 하나 더 있다는 것뿐이다 — 이벤트는 "어느 날에 속하지" 않는다.
--
-- ── 표식이 정확성의 임계 경로 밖에 있다 ───────────────────────────────────
-- 이 표식은 집계 대상을 정의하지 않는다. 배치는 여전히 그 날짜 전체를 재집계하고
-- 덮어쓴다(W3D3 §5 유지). 표식이 하는 일은 "다시 볼 날짜냐"를 알려주는 것뿐이라,
-- 표식이 틀려도 금액은 안 틀린다.
--
-- 다만 두 오류 방향은 대칭이 아니다:
--   안 셌는데 "셌다"(행을 잘못 지움) → 그 날짜를 다시 안 봄 → 증발.   치명적
--   셌는데 "안 셌다"(행이 남음)      → 같은 값을 다시 씀.           무해
-- 그래서 이 행의 삭제는 정산 쓰기와 반드시 같은 트랜잭션이어야 한다. 표식이 먼저
-- 커밋되면 정산이 실패했을 때 "셌다"만 남는다. 같은 tx 면 롤백이 안전한 쪽으로 떨어진다.
--
-- ── settlement_date 컬럼을 안 두는 이유 ───────────────────────────────────
-- V8 이 "KST 기준 며칠"이라는 뜻은 ZoneId 상수 한 곳(SettlementService.ZONE)에만
-- 존재한다고 못박았다. 여기 날짜를 미리 계산해 담으면 그 계산이 두 번째 거처가 되고,
-- 트리거가 채우려면 SQL 안에 'Asia/Seoul' 이 박힌다. journal_id 만 들고 날짜 변환은
-- 애플리케이션이 ZONE 으로 한다 — 존이 DB 로 새지 않는다.
-- =========================================

CREATE TABLE settlement_pending (
    -- journal 당 한 행. PK 가 곧 중복 방지다(트리거가 두 번 불려도 두 번째는 거부된다).
    journal_id BIGINT PRIMARY KEY REFERENCES journal(id)
);

-- ── 표식을 앱이 아니라 트리거가 넣는 이유 ────────────────────────────────
-- 앱(LedgerService 의 save 두 곳)에 두면 코드에 보이지만, journal 을 만드는 새 경로가
-- 생겼을 때 잊을 수 있고 그 누락이 조용하다 — 그 줄은 영원히 안 세지는데 아무도 모른다.
-- 트리거는 잊는 것이 불가능하다. 대가는 쓰기가 코드에서 안 보이는 것이고, 이 프로젝트엔
-- 이미 그 대가를 치른 전례가 있다(V5 trg_journal_balanced).
--
-- 같은 트랜잭션 안에서 실행되므로 journal 이 롤백되면 이 행도 같이 사라진다.
-- append-only 규율(W2D1 §5)은 안 건드린다 — journal/ledger_entry 에 컬럼을 더하지 않았다.
CREATE FUNCTION enqueue_settlement_pending() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO settlement_pending (journal_id) VALUES (NEW.id);
    RETURN NULL;   -- AFTER 트리거라 반환값은 무시된다
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_journal_settlement_pending
    AFTER INSERT ON journal
    FOR EACH ROW
    EXECUTE FUNCTION enqueue_settlement_pending();

-- 기존 journal 을 전부 대기열에 넣는다. 이 마이그레이션 이후로 불변식이 하나 성립해야
-- 하기 때문이다 — "모든 journal 은 세졌거나 대기 중이거나 둘 중 하나". 안 넣으면 V10
-- 이전에 증발한 줄이 영영 안 주워진다.
--
-- 대가는 첫 배치가 과거 날짜를 전부 한 번씩 다시 도는 것인데, 덮어쓰기라 같은 값을
-- 다시 쓸 뿐이다(W3D3 §5 를 고른 덕에 이 backfill 이 안전하다). 누적이었으면 이 한 줄이
-- 전체 이중계상이었다.
INSERT INTO settlement_pending (journal_id) SELECT id FROM journal;
